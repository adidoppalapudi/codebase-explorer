def test_skips_files_with_syntax_errors(repo, tmp_path):
    (repo / "app" / "broken.py").write_text("def broken(:\n    pass\n")

    report = index_repo(repo, tmp_path / "index.db")

    assert ("app/broken.py", "syntax error on line 1") in report.skipped
    assert search_code(report.db_path, "broken") == []


def test_signatures_with_one_line_bodies_comments_and_non_ascii(repo, tmp_path):
    (repo / "app" / "extra.py").write_text(
        'def tiny(): return 1\n'
        '\n'
        'def greet(name="José", sep: dict[str, int] = {"a": 1}) -> str:  # note: colon\n'
        '    """Say hi."""\n'
        '    return name\n',
        encoding="utf-8",
    )

    report = index_repo(repo, tmp_path / "index.db")

    tiny = only(report.db_path, "tiny")
    assert (tiny.signature, tiny.start_line, tiny.end_line) == ("def tiny()", 1, 1)
    greet = only(report.db_path, "greet")
    assert greet.signature == 'def greet(name="José", sep: dict[str, int] = {"a": 1}) -> str'
    assert (greet.start_line, greet.end_line) == (3, 5)
