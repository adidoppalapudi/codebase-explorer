def test_reindexing_replaces_instead_of_duplicating(repo, db):
    first = search_code(db, "authenticate", limit=50)
    index_repo(repo, db)
    assert search_code(db, "authenticate", limit=50) == first


def test_reindexing_drops_deleted_files(repo, db):
    (repo / "app" / "billing.py").unlink()
    index_repo(repo, db)
    assert search_code(db, "charge_card") == []


def test_skips_ignored_generated_and_unreadable_files(repo, tmp_path):
    def write(rel: str, content: str | bytes) -> None:
        path = repo / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content if isinstance(content, bytes) else content.encode())

    hidden = "def hidden_symbol():\n    pass\n"
    for rel in [".git/hooks/hook.py", ".venv/lib/site.py", "app/__pycache__/cached.py",
                "node_modules/pkg/x.py", "build/lib/app.py", "pkg.egg-info/x.py",
                "custom_env/lib/x.py", "app/messages_pb2.py"]:
        write(rel, hidden)
    write("custom_env/pyvenv.cfg", "home = /usr/bin\n")
    write("app/schema.py", "# @generated by a tool. DO NOT EDIT.\n" + hidden)
    write("app/blob.py", b"def hidden_symbol():\x00\n")
    write("app/latin1.py", "# caf\xe9\n".encode("latin-1") + hidden.encode())

    report = index_repo(repo, tmp_path / "index.db")

    assert search_code(report.db_path, "hidden_symbol") == []
    assert dict(report.skipped) == {
        "app/messages_pb2.py": "generated file",
        "app/schema.py": "generated file",
        "app/blob.py": "binary file",
        "app/latin1.py": "not UTF-8 text",
    }


def test_skips_symlinks_that_leave_the_repository(repo, tmp_path):
    outside = tmp_path / "outside.py"
    outside.write_text("def leaked_secret():\n    pass\n")
    try:
        os.symlink(outside, repo / "app" / "link.py")
    except OSError:
        pytest.skip("symlinks not available")

    report = index_repo(repo, tmp_path / "index.db")

    assert ("app/link.py", "symlink outside repository") in report.skipped
    assert search_code(report.db_path, "leaked_secret") == []


