import os
from pathlib import Path

import pytest

from explorer.indexer import index_repo
from explorer.retriever import search_code


def only(db: Path, name: str):
    matches = search_code(db, name, limit=50)
    exact = [m for m in matches if m.qualified_name == name]
    assert len(exact) == 1, f"expected one {name}, got {matches}"
    return exact[0]


def test_class_methods_and_function_have_exact_line_ranges(db):
    expected = {
        "UserService": ("class", "app/auth.py", 6, 17),
        "UserService.__init__": ("method", "app/auth.py", 9, 10),
        "UserService.authenticate": ("method", "app/auth.py", 12, 17),
        "hash_password": ("function", "app/auth.py", 20, 22),
    }
    for name, (kind, path, start, end) in expected.items():
        match = only(db, name)
        assert (match.kind, match.path, match.start_line, match.end_line) == (kind, path, start, end)


def test_signatures(db):
    assert only(db, "UserService").signature == "class UserService"
    assert only(db, "UserService.authenticate").signature == (
        "def authenticate(self, username: str, password: str) -> bool"
    )
    assert only(db, "UserRepository.find_user").signature == "async def find_user(self, username)"
    assert only(db, "UserRepository.save_user").signature == (
        "def save_user( conn, username: str, password_hash: str, ) -> None"
    )


def test_decorated_definitions_start_at_the_decorator(db):
    match = only(db, "open_connection")
    assert (match.start_line, match.end_line) == (7, 14)
    match = only(db, "UserRepository.save_user")
    assert (match.start_line, match.end_line) == (27, 33)


def test_report_counts(repo, tmp_path):
    report = index_repo(repo, tmp_path / "index.db")
    # 4 symbols in auth.py, 5 in db.py, 2 in billing.py. __init__.py has none.
    assert (report.files_indexed, report.symbols_indexed) == (4, 11)
